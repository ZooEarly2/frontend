import type { MathFruit } from '@/scenarios/types';

/**
 * 셀 과일을 그림 위에 놓는다.
 *
 * 과일을 그림에 굽지 않는다. 종류 셋 × 개수 다섯이면 열다섯 장이 되는데,
 * 그림 하나를 고칠 때마다 열다섯 장을 다시 만들어야 하고 배치도 손댈 수 없다.
 * 얹으면 한 장으로 끝나고, 아이 화면 크기에 맞춰 같이 커진다.
 *
 * 자리는 **비율로** 잡는다. 카드가 정사각(aspect-ratio 1/1)이라 폭이 바뀌어도
 * 과일과 토끼의 관계가 그대로다.
 */

/**
 * 과일이 앉는 자리. 카드 크기의 백분율이다.
 *
 * 토끼는 그림 오른쪽 아래(가로 71% 부터, 세로 45% 부터)에 있고 물음표를 달고
 * 서 있다. 그 자리를 피해 **왼쪽 위 넓은 크림 영역**에만 놓는다 — 토끼를 가리면
 * 누가 묻고 있는지가 사라진다.
 *
 * 개수마다 배치를 따로 적은 이유가 있다. 자동으로 배열하면 네 개일 때 한 줄로
 * 늘어서서 마지막 하나가 토끼에 닿거나, 다섯 개일 때 서로 겹친다. 다섯 가지뿐이니
 * 사람이 보고 정하는 편이 낫다. 아이가 한눈에 세려면 **줄이 가지런해야** 한다.
 */
const SPOTS: Record<number, { x: number; y: number }[]> = {
  1: [{ x: 36, y: 46 }],
  2: [
    { x: 26, y: 46 },
    { x: 46, y: 46 },
  ],
  3: [
    { x: 17, y: 46 },
    { x: 36, y: 46 },
    { x: 55, y: 46 },
  ],
  4: [
    { x: 24, y: 30 },
    { x: 44, y: 30 },
    { x: 24, y: 62 },
    { x: 44, y: 62 },
  ],
  5: [
    { x: 17, y: 30 },
    { x: 36, y: 30 },
    { x: 55, y: 30 },
    { x: 26, y: 62 },
    { x: 46, y: 62 },
  ],
};

/**
 * 과일 한 개의 폭(카드 대비 %).
 *
 * 다섯 개가 서로 3% 씩 떨어지고, 맨 왼쪽이 가장자리에서 9% 안쪽에 서는 값이다.
 * 더 키우면 붙어서 몇 개인지 세기 어렵고, 줄이면 390px 카드에서 62px 아래로
 * 내려가 작은 폰에서 무엇인지 안 보인다.
 */
const SIZE = 16;

export function FruitCount({ fruit, count }: { fruit: MathFruit; count: number }) {
  const spots = SPOTS[count] ?? SPOTS[1];
  return (
    <>
      {spots.map((spot, index) => (
        <img
          key={`${fruit.id}-${index}`}
          className="fruit"
          src={fruit.image}
          alt=""
          aria-hidden
          style={{
            left: `${spot.x}%`,
            top: `${spot.y}%`,
            width: `${SIZE}%`,
            /*
              하나씩 차례로 놓인다. 한꺼번에 나타나면 아이 눈에는 "덩어리" 라
              세는 대상이 아니라 무늬로 보인다. 90ms 씩 밀어 놓으면 놓이는 것을
              눈으로 따라가게 되고, 그게 곧 세는 연습이다.
            */
            animationDelay: `${index * 90}ms`,
          }}
        />
      ))}
    </>
  );
}
